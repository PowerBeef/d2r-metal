#!/usr/bin/env python3
# 自动探索（乱按）：按种子随机生成一串玩家操作（按键、摇杆、点界面、点世界、停一下），当作场景交给场景运行器跑（dm/tools/scenario.py），
# 用场景同样的判据判这一局（崩溃、红标事件、日志红标行、消毒器报告、看门狗）；红了就先重跑一次看能不能复现，再用增量调试（ddmin）把操作串缩到还以同样方式红的最短一串，写成 minimal.scn。
#   explore.py run [--seed N] [--episodes K] [--steps N] [--save 存档] [--dmhost 宿主] [--allow-red 码,…] [--budget 次数] [--no-shrink] [--window]
#   结果目录 $DM_ROOT/run/explore/<时刻>_<种子>/：每局的场景文件 episode_<k>.scn 与其结果目录，红了另有 minimal.scn；判定行 EXPLORE OK|RED，末行 RESULT {json}
#   生成的操作串只用场景运行器认得的步骤，所以 minimal.scn 就是能直接重放的场景（scenario.py run minimal.scn）；只用不带断言的操作（open_pause / close_pause 这类宏自己会判红），也不生成 quit / crash / app / background 这些会主动结束或打断这一局的步骤
#   作为模块：actions(种子, 个数) 生成操作串，ddmin(操作串, 判定, 预算) 缩短，signature(结果) 取红因的指纹（单测用）
# Automatic exploration (monkey): generates a seeded random sequence of player actions (buttons, stick, UI taps, world taps, short pauses), hands it to the scenario runner as a scenario (dm/tools/scenario.py),
# and judges the run by the same criteria as scenarios (crash, red events, red log lines, sanitizer reports, watchdog); when it goes red, it is first rerun once to see whether it reproduces, then delta debugging (ddmin) shrinks the sequence to the shortest one that still goes red the same way, written as minimal.scn.
#   explore.py run [--seed N] [--episodes K] [--steps N] [--save save] [--dmhost host] [--allow-red code,...] [--budget runs] [--no-shrink] [--window]
#   Result folder $DM_ROOT/run/explore/<time>_<seed>/: each episode's scenario file episode_<k>.scn and its result folder, plus minimal.scn when red; verdict line EXPLORE OK|RED, last line RESULT {json}
#   The generated sequences only use steps the scenario runner knows, so minimal.scn is a scenario that replays directly (scenario.py run minimal.scn); only actions without assertions are used (macros such as open_pause / close_pause go red by themselves), and quit / crash / app / background, which end or interrupt the run on purpose, are never generated
#   As a module: actions(seed, count) generates a sequence, ddmin(sequence, predicate, budget) shrinks it, signature(result) takes the fingerprint of the red reason (used by the unit tests)
import argparse
import datetime
import json
import math
import os
import random
import re
import sys
from typing import Any

HERE = os.path.dirname(os.path.abspath(__file__))
DM_ROOT = os.environ.get('DM_ROOT') or os.path.expanduser('~/dm-work')
KEYS = ('A', 'B', 'X', 'Y', 'L', 'R', 'ZL', 'ZR', 'PLUS', 'MINUS', 'LEFT', 'UP', 'RIGHT', 'DOWN', 'LS', 'RS')
# (权重, 生成函数)：按键与点按为主，摇杆走动其次；暂停菜单靠乱按的键打开 | (weight, generator): mostly buttons and taps, stick walking next; the pause menu is reached through the random buttons
GEN = (
    (30, lambda r: f'press {r.choice(KEYS)} {r.randint(3, 20)}'),
    (15, lambda r: f'stick {r.choice((-1, -0.5, 0, 0.5, 1))} {r.choice((-1, -0.5, 0, 0.5, 1))} {r.randint(10, 60)}'),
    (20, lambda r: f'tap {r.uniform(0.05, 0.95):.3f} {r.uniform(0.05, 0.95):.3f}'),
    (15, lambda r: f'world_tap {r.uniform(0.2, 0.8):.3f} {r.uniform(0.2, 0.8):.3f}'),
    (15, lambda r: f'sleep {r.choice((0.2, 0.5, 1))}'),
)


def actions(seed, n):
    """按种子生成 n 步操作（同种子同结果）。 | Generate n action steps from the seed (same seed, same result)."""
    r = random.Random(seed); total = sum(w for w, _ in GEN); out = []
    for _ in range(n):
        x = r.uniform(0, total)
        for w, g in GEN:
            x -= w
            if x <= 0: out.append(g(r)); break
        else: out.append(GEN[-1][1](r))
    return out


def scenario_text(name, save, steps, allow, timeout):
    allow_kw = f' allow={allow}' if allow else ''
    return '\n'.join([f'# explore.py 生成 | generated by explore.py: {name}', f'name {name}', f'save {save}', f'timeout {timeout}', '', 'enter_game', *steps, '',
                      f'check no_red{allow_kw}', 'check no_red_log', '']) + '\n'


def _norm(s):
    return re.sub(r'0x[0-9a-f]+|\b\d+(\.\d+)?\b', '#', s or '')[:120]   # 只抹单独的数字与十六进制，名字里的数字（fn_455a80）留着 | blank only standalone numbers and hex, keep digits inside names (fn_455a80)


def signature(res):
    """红因的指纹：同一个毛病在不同操作串里给同一个值（数字与地址抹掉）；没红返回 None。 | Fingerprint of the red reason: the same fault gives the same value across different sequences (numbers and addresses blanked); None when not red."""
    if res.get('verdict') != 'RED': return None
    reason = res.get('reason') or ''
    m = re.search(r'crash (\w+) at ([^;]+)', reason)
    if m: return f'crash {m.group(1)} at {m.group(2).split(" (")[0].strip()}'   # 崩溃地点原样：模块偏移跨次运行不变 | the crash site as is: module offsets do not change between runs
    for c in res.get('checks') or []:
        if c.get('ok'): continue
        d = c.get('detail') or ''
        code = re.search(r'"code": "([0-9a-f]{8})"', d)
        if code: return f'red {code.group(1)}'
        kind = re.search(r'"ev": "(\w+)"', d)
        if kind: return f'event {kind.group(1)}'
        return f"{c.get('check')}: {_norm(d.split(': ', 1)[-1])}"
    f = res.get('failed') or {}
    return f"step {_norm(str(f.get('line', '')).split(' ')[0])}: {_norm(f.get('reason'))}"


def ddmin(items, fails, budget):
    """增量调试：把 items 缩到仍让 fails() 为真的较短子序列（保持原次序）；最多试 budget 次。返回 (结果, 试的次数)。 | Delta debugging: shrink items to a shorter subsequence for which fails() still holds (original order kept); at most budget tries. Returns (result, tries)."""
    runs = 0
    if budget > 0 and items:
        runs += 1
        if fails([]): return [], runs
    n = 2
    while len(items) >= 2 and runs < budget:
        size = math.ceil(len(items) / n); parts = [items[i:i + size] for i in range(0, len(items), size)]
        done = False
        for part in parts if n > 2 else []:   # n = 2 时子集与补集是同两组，只试补集 | at n = 2 the subsets and complements are the same two groups: try complements only
            if runs >= budget: break
            runs += 1
            if fails(part): items, n, done = part, 2, True; break
        if not done:
            for i in range(len(parts)):
                if runs >= budget: break
                comp = [x for j, p in enumerate(parts) if j != i for x in p]
                runs += 1
                if fails(comp): items, n, done = comp, max(n - 1, 2), True; break
        if not done:
            if n >= len(items): break
            n = min(len(items), n * 2)
    return items, runs


class Explorer:
    def __init__(self, a):
        self.a = a
        self.out = a.out or os.path.join(DM_ROOT, 'run', 'explore', f"{datetime.datetime.now().strftime('%Y%m%d_%H%M%S')}_{a.seed}")
        os.makedirs(self.out, exist_ok=True); self.n = 0
        if a.dmhost: os.environ['SCN_DMHOST'] = os.path.abspath(a.dmhost)
        sys.path.insert(0, HERE); import scenario   # noqa: PLC0415  # pyright: ignore[reportMissingImports]
        self.scenario = scenario

    def run(self, tag, steps):
        """把一串操作当场景跑一次：返回 (结果, 指纹)。 | Run a sequence of actions once as a scenario: returns (result, fingerprint)."""
        self.n += 1
        path = os.path.join(self.out, f'{tag}.scn')
        with open(path, 'w', encoding='utf-8') as f: f.write(scenario_text(f'explore_{tag}', self.a.save, steps, self.a.allow_red, self.a.timeout))
        try: res, _ = self.scenario.Runner(path, 'cli', os.path.join(self.out, tag), not self.a.window).go()
        except self.scenario.ScenarioError as e: res = dict(verdict='RED', reason=str(e))
        return res, signature(res)

    def shrink(self, k, steps, sig):
        """把第 k 局的操作串缩到仍以同一指纹红的最短一串，写 minimal_<k>.scn。 | Shrink episode k's sequence to the shortest one that still goes red with the same fingerprint, written as minimal_<k>.scn."""
        tries = 0
        def fails(sub):
            nonlocal tries
            tries += 1; _, s = self.run(f'shrink_{k}_{tries}', sub)
            print(f"  缩 | shrink {tries}: {len(sub)} 步 | steps → {s or 'OK'}", flush=True); return s == sig
        small, runs = ddmin(steps, fails, self.a.budget)
        mpath = os.path.join(self.out, f'minimal_{k}.scn')
        with open(mpath, 'w', encoding='utf-8') as f: f.write(scenario_text(f'explore_minimal_{k}', self.a.save, small, self.a.allow_red, self.a.timeout))
        print(f'  最短复现 | minimal reproducer: {len(small)} 步 | steps（试了 {runs} 次 | {runs} tries）→ {mpath}', flush=True)
        return dict(minimal=mpath, minimal_steps=len(small), shrink_runs=runs)

    def go(self):
        report: dict[str, Any] = dict(name='explore', seed=self.a.seed, episodes=[], dir=self.out)
        for k in range(self.a.episodes):
            seed = self.a.seed * 1000 + k; steps = actions(seed, self.a.steps)
            res, sig = self.run(f'episode_{k}', steps)
            ep: dict[str, Any] = dict(episode=k, seed=seed, steps=len(steps), verdict=res.get('verdict'), signature=sig, dir=res.get('dir'))
            report['episodes'].append(ep)
            print(f"EPISODE {k} {res.get('verdict')} {len(steps)} 步 | steps" + (f'：{sig}' if sig else ''), flush=True)
            if not sig: continue
            again, sig2 = self.run(f'episode_{k}_again', steps)   # 先看能不能复现 | first see whether it reproduces
            ep['reproduced'] = sig2 == sig
            if sig2 != sig:
                print(f'  重跑没复现（{sig2 or "OK"}）：不缩，保留 episode_{k}.scn | the rerun did not reproduce ({sig2 or "OK"}): not shrinking, keeping episode_{k}.scn'); continue
            if not self.a.no_shrink: ep.update(self.shrink(k, steps, sig))
        red = [e for e in report['episodes'] if e['signature']]
        if red:
            e = red[0]
            print(f"EXPLORE RED {len(red)}/{len(report['episodes'])} 局红 | episodes red；第一个 | first: episode {e['episode']}：{e['signature']}" + (f"；最短 {e['minimal_steps']} 步 → {e['minimal']}" if e.get('minimal') else ''))
        else:
            print(f"EXPLORE OK {len(report['episodes'])} 局、每局 {self.a.steps} 步，没有红 | episodes of {self.a.steps} steps, nothing red（共跑 {self.n} 次 | {self.n} runs）")
        report.update(verdict='RED' if red else 'OK', runs=self.n)
        with open(os.path.join(self.out, 'explore.json'), 'w', encoding='utf-8') as f: json.dump(report, f, ensure_ascii=False, indent=1)
        print('RESULT ' + json.dumps(report, ensure_ascii=False))
        return 1 if red else 0


def main(argv):
    ap = argparse.ArgumentParser(prog='explore.py', description='Seeded random play through the scenario runner, with shrinking of red runs to a minimal scenario.')
    sub = ap.add_subparsers(dest='cmd', required=True)
    r = sub.add_parser('run')
    r.add_argument('--seed', type=int, default=1); r.add_argument('--episodes', type=int, default=1); r.add_argument('--steps', type=int, default=40)
    r.add_argument('--save', default='warlock'); r.add_argument('--dmhost', help='host executable to run (SCN_DMHOST), for example dm/host/dmhost_asan')
    r.add_argument('--allow-red', default='', help='comma-separated red event codes to tolerate'); r.add_argument('--timeout', type=int, default=300)
    r.add_argument('--budget', type=int, default=24, help='at most this many shrinking runs per red episode'); r.add_argument('--no-shrink', action='store_true')
    r.add_argument('--window', action='store_true', help='show the game window (default headless)'); r.add_argument('--out')
    g = sub.add_parser('gen', help='print the generated steps of one episode'); g.add_argument('--seed', type=int, default=1); g.add_argument('--steps', type=int, default=40)
    a = ap.parse_args(argv)
    sys.path.insert(0, HERE); import scenario   # noqa: PLC0415  # pyright: ignore[reportMissingImports]
    held = scenario.game_lock(__file__, argv, f"explore seed {getattr(a, 'seed', '?')} ~{getattr(a, 'episodes', 1)} min", a.cmd == 'run' and a.window)   # 开窗跑局先拿 Mac 游戏锁 | runs that open a window take the Mac game lock first
    if held is not None: return held
    if a.cmd == 'gen':
        for s in actions(a.seed, a.steps): print(s)
        return 0
    return Explorer(a).go()


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
