#!/usr/bin/env python3
"""Routes that cast every skill of a class, for the pipeline survey and the warm-up seed (pso_seed.py record --set skills).

A skill's effects are drawn with pipelines no walk through the areas builds, and some of them cannot wait for a pipeline (they write depth
or stencil), so their first use would compile in the frame. A route here makes a hero of one class cast each of the class's skills once
or twice in the Blood Moor among a few monsters.

Nothing about the skills is kept in the repository: their numbers, required levels and which hand may cast them are read from the game's
own skills table in this machine's game files when a route is made.

  skill_routes.py classes            the classes, their figure on the creation screen and their generated save
  skill_routes.py hero <class>       prints the scenario that makes the class's hero (save_ref_hero_<class>; windowed in the background)
  skill_routes.py route <class>      prints the route: the hero is given the level and the points by the test switches, each skill is
                                     learned in an order that meets its prerequisites, made the right-hand skill with the game's own
                                     packet (the control port's c2s) and cast with the right mouse button in PC control mode
A class is its code in the game's tables: ama sor nec pal bar dru ass war.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DM_ROOT = os.environ.get('DM_ROOT') or os.path.expanduser('~/dm-work')
ROMFS_DATA = os.path.join(DM_ROOT, 'data', 'switch', '3.3.94012', 'Update', 'RomFS', 'data')
# class code -> the figure's widget name on the character creation screen
CLASSES = {'ama': 'Amazon', 'sor': 'Sorceress', 'nec': 'Necromancer', 'pal': 'Paladin', 'bar': 'Barbarian', 'dru': 'Druid', 'ass': 'Assassin', 'war': 'Warlock'}


def save_name(cls):
    return 'warlock_hero' if cls == 'war' else f'hero_{cls}'   # the Warlock's was made first, by scenarios/saves/warlock_hero.scn


def skills(cls, data=ROMFS_DATA):
    """[(id, required level, passive, right hand)] of the class's skills, in an order that meets every prerequisite (by required level, then id)."""
    sys.path.insert(0, HERE)
    import dmx  # noqa: PLC0415
    dmx.ROOT = data
    lines = dmx.get('data:data/global/excel/skills.txt').decode('latin1').split('\r\n')
    h = lines[0].split('\t'); ci = {n: i for i, n in enumerate(h)}
    out = []
    for line in lines[1:]:
        r = line.split('\t')
        if len(r) <= ci['charclass'] or r[ci['charclass']] != cls: continue
        g = lambda c: r[ci[c]] if ci[c] < len(r) else ''   # noqa: E731
        out.append((int(g('*Id')), int(g('reqlevel') or 1), bool(g('passive')), bool(g('rightskill'))))
    return sorted(out, key=lambda s: (s[1], s[0]))


def hero_text(cls):
    name = save_name(cls)
    return '\n'.join([
        f'# generated by dm/tools/skill_routes.py hero {cls}: a new hero of this class, made on the character creation screen (the class is picked by',
        f'# tapping its figure), entered once and exported as save_ref_{name}. It stays in the local workspace and is never committed.',
        f'name gen_{name}', 'requires cli', 'save warlock', 'env DM_VKBD=1', 'timeout 180', '',
        'expect main_menu timeout=120', 'sleep 1', 'press PLUS', 'sleep 1', 'press DOWN', 'press A', 'expect_state panels~=CharacterCreatePanel timeout=20', 'sleep 1.5',
        f'tap_ui {CLASSES[cls]}', 'sleep 1', 'press A', 'expect_state panels~=CharacterOptionsPanel timeout=10', 'sleep 1', 'press A',
        'expect_state focus_panel=CharacterCreateNamePanel focus=InputText timeout=10', 'sleep 1', 'press A', 'sleep 1.5', 'fe "0 pads X,A,RIGHT,A,RIGHT,A"', 'sleep 2.5', 'fe "0 pad PLUS"',
        'expect game_enter timeout=60', 'expect loading_done timeout=120', 'expect_state in_game=true level=1 dead=false timeout=20', 'save_now timeout=8',
        f'export_save {name} overwrite=1', 'quit', 'check no_red', 'check no_red_log']) + '\n'


def route_text(cls, env=None, backend=None, data=ROMFS_DATA):
    sk = skills(cls, data)
    if not sk: raise SystemExit(f'🔴 no skills of class {cls} in the game\'s table')
    adds = ','.join(f'{s[0]}:1' for s in sk) + f',{sk[0][0]}:1'   # the switch's last entry is not learned: end on a second point for the first skill
    extra = ' '.join(f'{k}={v}' for k, v in (env or {}).items())
    lines = [f'# generated by dm/tools/skill_routes.py route {cls}: the class\'s hero casts every skill of the class in the Blood Moor (see bench/skill_tour.scn,',
             '# the Warlock\'s route, for how)', f'name skill_tour_{cls}']
    if backend == 'mac-app': lines.append('requires mac-app')
    lines += [f'save {save_name(cls)}', 'timeout 480', 'env DM_ROMFS_OVERLAY=auto-mac DM_PC_MODE=1 DM_GAME_SEED=305419896 DM_TEST_KEEP_LIFE=1',
              f'env DM_TEST_STAT=12=40,5=40,8=256000,9=256000 DM_TEST_SKILL_ADD=300:{adds}']
    if extra: lines.append('env ' + extra)
    lines += ['', 'expect main_menu timeout=120', 'enter_game', 'sleep 16', 'goto 2', 'spawn cls=19 count=6', 'sleep 3']
    for sid, _lvl, passive, right in sk:
        if passive: continue
        hand = '0000' if right else '0080'   # a skill the right hand may not take goes on the left
        btn = 'right' if right else 'left'
        lines += [f'c2s hex=3c{sid & 0xff:02x}{sid >> 8:02x}{hand}ffffffff', 'sleep 0.4', f'kbm btn={btn} x=0.62 y=0.40', f'kbm btn={btn} x=0.62 y=0.40 up=1', 'sleep 1.6',
                  f'kbm btn={btn} x=0.42 y=0.46', f'kbm btn={btn} x=0.42 y=0.46 up=1', 'sleep 2.0']
    return '\n'.join(lines + ['sleep 3', 'quit', 'check no_red', 'check no_red_log']) + '\n'


def main(argv):
    if len(argv) >= 1 and argv[0] == 'classes':
        for c, w in CLASSES.items(): print(f'{c}\t{w}\tsave_ref_{save_name(c)}')
        return 0
    if len(argv) == 2 and argv[0] in ('hero', 'route') and argv[1] in CLASSES:
        sys.stdout.write(hero_text(argv[1]) if argv[0] == 'hero' else route_text(argv[1])); return 0
    print(__doc__); return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
